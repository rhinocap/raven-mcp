// Generates <store>/builds/<id>/PROMPT.md for all 18 builds from the sealed assignment.
// The instruction block is the ONLY thing that differs; TASK.md is appended verbatim.
//
// Three things are deliberately identical across arms and are worth naming, because round 4
// failed on exactly this kind of unexamined difference:
//
//  1. Every arm drives the same shim with the same call syntax. Arm A is not handed a block
//     of pre-composed text; it calls the tool, like the others.
//  2. No arm is told a filesystem path. The shim fills paths in from each tool's own schema,
//     and redacts every absolute path out of every result.
//  3. Arm A is NOT told to call the composer twice. The composer's own grounding response
//     says to. Putting the two-call instruction in arm A's prompt would make "the composer
//     helped" and "being told to do two passes helped" inseparable in the prose as well as
//     in the tool, and only the latter is avoidable.
//
// The profile name and project name are disclosed to every arm. They are arguments, not
// discriminating facts: `verify-fixture5.mjs` asserts that nothing reachable through
// get_taste_profile decides any of the sixteen checks.

import { readFileSync, writeFileSync, mkdirSync, copyFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = dirname(fileURLToPath(import.meta.url));
// The fixture store and the workspace are DIFFERENT directories, and only the workspace is
// ever named to a builder. The first draft of this file put the shim and the build dirs
// inside the store, which meant every prompt disclosed the store's path in its own tool
// invocation line — round 4's defect rebuilt, one directory over. Nothing a builder is
// handed now names the store.
const STORE = '/Users/accunliffe/.pregate-r5-8f3a2c';
const WORK = '/Users/accunliffe/.r5-workspace';
const TASK = readFileSync(join(HERE, 'TASK.md'), 'utf8');
const CLI = join(WORK, 'raven-cli.mjs');

// Sealed before any build. Generated by a fixed-seed Fisher–Yates over six of each arm,
// seed = the round tag "pregate-r5-8f3a2c", so it is reproducible from this file alone.
const ASSIGNMENT = {
  b01: 'B2', b02: 'B1', b03: 'B2', b04: 'A',  b05: 'A',  b06: 'B1',
  b07: 'B1', b08: 'A',  b09: 'B1', b10: 'B2', b11: 'B1', b12: 'A',
  b13: 'B2', b14: 'A',  b15: 'B1', b16: 'B2', b17: 'A',  b18: 'B2',
};

const HOWTO = (arm) => `
A Raven MCP server is connected. Invoke a tool like this:

    node ${CLI} ${arm} <tool_name> '<json-args>'

Run it with a tool name it does not have to see the tools available to you. The taste profile
is named \`ledger\`, the project is named \`arena\`, and the surface is
\`reconciliation review screen\`. The tools take no filesystem paths — they resolve their own,
and none is disclosed to you.
`.trim();

const BLOCK = {
  A: `## Instructions

Call \`compose_build_prompt\` and follow what it gives you, then do the task.

${HOWTO('A')}`,

  B1: `## Instructions

Call \`read_design_md\`, \`get_taste_profile\` and \`audit_taste\` yourself, then do the task.

${HOWTO('B1')}`,

  B2: `## Instructions

A Raven MCP server is connected with the full local tool surface, including the design system,
the taste profile and its bindings, per-project taste decisions, and the project's Decision
Graph. Use whatever you need, then do the task.

${HOWTO('B2')}`,
};

const RULES = (id) => `
---

## Output

Write exactly two files, both into \`${join(WORK, 'builds', id)}/\`:

- \`index.html\` — the build
- \`NOTES.md\` — as specified in the task brief

## Ground rules

- The tools are your access path to the design system. Do not go looking on the filesystem
  for design-system files, taste stores, decision records, or anything belonging to this
  exercise; anything found that way is outside the configuration you are being asked to
  build under.
- Do not read any other build directory, and do not read anything under a \`pregate\`
  directory. Other builds of this same task exist; reading one is not the exercise.
- Do not ask questions. Everything you need is in this file or reachable through the tools.
  Where a detail is genuinely unsettled, decide, build, and say so in \`NOTES.md\`.
- Finish. A partial build scores as a partial build.
`;

mkdirSync(WORK, { recursive: true });
copyFileSync(join(HERE, 'raven-cli-stub.mjs'), CLI);

for (const [id, arm] of Object.entries(ASSIGNMENT)) {
  const dir = join(WORK, 'builds', id);
  mkdirSync(dir, { recursive: true });
  writeFileSync(join(dir, 'PROMPT.md'), `${BLOCK[arm]}\n\n---\n\n${TASK}\n${RULES(id)}`);
}
writeFileSync(join(HERE, 'assignment.json'), JSON.stringify(ASSIGNMENT, null, 2) + '\n');

// Fail loudly rather than shipping a prompt that leaks the store, since that is the exact
// defect that ended round 4 and it is invisible by inspection once eighteen files exist.
const leaks = Object.keys(ASSIGNMENT).filter((id) =>
  readFileSync(join(WORK, 'builds', id, 'PROMPT.md'), 'utf8').includes(STORE));
if (leaks.length) {
  console.error(`STORE PATH LEAKED into ${leaks.length} prompt(s): ${leaks.join(', ')}`);
  process.exit(1);
}
console.log(`wrote ${Object.keys(ASSIGNMENT).length} prompts under ${join(WORK, 'builds')}`);
console.log('no prompt names the fixture store.');
